"""Generate the reference section of the documentation (docs/reference/) from the code.

Everything in docs/reference/ that can be enumerated comes from the objects the program itself
uses: the MCP tool registry, the CLI parser, the Config dataclass, the default schedule, the
alert rules, the feature-flag map, the dashboard router and the visible-error catalog. Nothing
is copied by hand, so nothing can drift: tests/test_referencia_em_dia.py renders the same pages
in memory and fails when the files on disk differ.

Run from the repository root:

    PYTHONPATH=src python scripts/gerar_referencia.py           # write docs/reference/
    PYTHONPATH=src python scripts/gerar_referencia.py --check   # exit 1 if anything is stale

English text that the code does not carry (what a config key or an environment variable does)
lives in docs/reference/_text/*.toml, keyed by name. A key with no text is rendered as
"(not documented yet)" and listed by --check.
"""

from __future__ import annotations

import argparse
import ast
import asyncio
import csv
import json
import re
import sys
import tomllib
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[1]
SRC = RAIZ / "src" / "delegation_core"
DESTINO = RAIZ / "docs" / "reference"
TEXTOS = DESTINO / "_text"
SEM_TEXTO = "(not documented yet)"

CABECALHO = ("<!-- Generated by scripts/gerar_referencia.py from the code. Do not edit by hand:\n"
             "     change the code (or docs/reference/_text/) and run the script again. -->\n\n")


# ── helpers ──────────────────────────────────────────────────────────────────

def _textos(nome: str) -> dict:
    p = TEXTOS / f"{nome}.toml"
    if not p.exists():
        return {}
    return tomllib.loads(p.read_text(encoding="utf-8"))


def _celula(texto) -> str:
    """Text safe inside a Markdown table cell."""
    return str(texto).replace("|", "\\|").replace("\n", " ").strip()


def _tipo(schema: dict) -> str:
    if "anyOf" in schema:
        return " or ".join(_tipo(s) for s in schema["anyOf"])
    t = schema.get("type", "any")
    if t == "array":
        return f"array of {_tipo(schema.get('items', {}))}"
    return t


def _valor(v) -> str:
    return "`" + json.dumps(v, ensure_ascii=False) + "`"


def _ancora(nome: str) -> str:
    return re.sub(r"[^a-z0-9_-]", "", nome.lower().replace(" ", "-"))


# ── MCP tools ────────────────────────────────────────────────────────────────

def _ferramentas():
    from delegation_core import disponibilidade, escopos, server
    ferramentas = {t.name: t for t in asyncio.run(server.mcp.list_tools())}
    chave_de = {}
    for chave, nomes in disponibilidade.POR_CHAVE.items():
        for n in nomes:
            chave_de[n] = chave
    return ferramentas, chave_de, disponibilidade, escopos


def pagina_ferramentas() -> str:
    ferramentas, chave_de, disp, escopos = _ferramentas()
    linhas = [CABECALHO, "# MCP tools\n\n",
              f"The daemon registers **{len(ferramentas)} tools**. A tool tied to a config key is hidden from\n"
              "clients while that key is off (see [feature flags](feature-flags.md)); `capabilities()` lists\n"
              "the hidden ones and why. A client whose token has the `read` scope can only call tools marked\n"
              "*read*.\n\n",
              "| Tool | Access | Needs |\n|---|---|---|\n"]
    for nome in sorted(ferramentas):
        acesso = "write" if nome in escopos.ESCRITA else "read"
        precisa = []
        if nome in chave_de:
            chave = chave_de[nome]
            precisa.append(f"`{chave}`" + (" (off by default)" if chave in disp.PADRAO_FALSO else ""))
        if nome in disp.EXTRA_GRAFO:
            precisa.append("extra `[graph]`")
        linhas.append(f"| [`{nome}`](#{_ancora(nome)}) | {acesso} | {', '.join(precisa) or ''} |\n")
    for nome in sorted(ferramentas):
        t = ferramentas[nome]
        linhas.append(f"\n## {nome}\n\n")
        linhas.append(((t.description or "").strip() or SEM_TEXTO) + "\n\n")
        acesso = "write" if nome in escopos.ESCRITA else "read"
        linhas.append(f"**Access:** {acesso}")
        if nome in chave_de:
            linhas.append(f" · **Config key:** `{chave_de[nome]}`")
        if nome in disp.EXTRA_GRAFO:
            linhas.append(" · **Needs:** extra `[graph]`")
        linhas.append("\n\n")
        props = t.parameters.get("properties", {})
        exigidos = set(t.parameters.get("required", []))
        if not props:
            linhas.append("No parameters.\n")
            continue
        linhas.append("| Parameter | Type | Required | Default |\n|---|---|---|---|\n")
        for p, sch in props.items():
            padrao = _valor(sch["default"]) if "default" in sch else ""
            linhas.append(f"| `{p}` | {_celula(_tipo(sch))} | {'yes' if p in exigidos else 'no'} | {_celula(padrao)} |\n")
    return "".join(linhas)


def pagina_flags() -> str:
    from delegation_core import disponibilidade as disp
    linhas = [CABECALHO, "# Feature flags\n\n",
              "Config keys that switch a group of tools on or off. While a key is off the tools in its\n"
              "row are not offered to clients at all, and `capabilities()` reports them under\n"
              "`hidden_tools` with the key that would bring them back.\n\n",
              "| Config key | Default | Tools |\n|---|---|---|\n"]
    for chave in sorted(disp.POR_CHAVE):
        padrao = "off" if chave in disp.PADRAO_FALSO else "on"
        nomes = ", ".join(f"[`{n}`](tools.md#{_ancora(n)})" for n in sorted(disp.POR_CHAVE[chave]))
        linhas.append(f"| [`{chave}`](config.md#{_ancora(chave)}) | {padrao} | {nomes} |\n")
    linhas.append("\nTools that need the optional `[graph]` extra (tree-sitter) are hidden when it is not\n"
                  "installed: " + ", ".join(f"`{n}`" for n in disp.EXTRA_GRAFO) + ".\n")
    return "".join(linhas)


# ── config.json ──────────────────────────────────────────────────────────────

def _campos_do_config():
    from dataclasses import MISSING, fields

    from delegation_core.config import Config
    arvore = ast.parse((SRC / "config.py").read_text(encoding="utf-8"))
    anotacoes = {}
    for no in ast.walk(arvore):
        if isinstance(no, ast.ClassDef) and no.name == "Config":
            for x in no.body:
                if isinstance(x, ast.AnnAssign) and isinstance(x.target, ast.Name):
                    anotacoes[x.target.id] = ast.unparse(x.annotation)
    saida = []
    for f in fields(Config):
        if f.default is not MISSING:
            padrao = f.default
        elif f.default_factory is not MISSING:
            padrao = f.default_factory()
        else:
            padrao = None
        saida.append((f.name, anotacoes.get(f.name, str(f.type)), padrao))
    return saida


def pagina_config() -> str:
    from delegation_core import disponibilidade as disp
    textos = _textos("config")
    campos = _campos_do_config()
    linhas = [CABECALHO, "# Configuration keys (`config.json`)\n\n",
              f"`~/.delegation_core/config.json` accepts **{len(campos)} keys**. A key that is absent takes the\n"
              "default below; a key the program does not know is ignored, and `delegation-core doctor`\n"
              "reports it. Paths may start with `~`.\n\n",
              "| Key | Type | Default |\n|---|---|---|\n"]
    for nome, tipo, padrao in campos:
        linhas.append(f"| [`{nome}`](#{_ancora(nome)}) | `{_celula(tipo)}` | {_celula(_valor(padrao))} |\n")
    for nome, tipo, padrao in campos:
        linhas.append(f"\n## {nome}\n\n")
        linhas.append(f"**Type:** `{tipo}` · **Default:** {_valor(padrao)}\n\n")
        linhas.append((textos.get(nome, {}).get("description", "").strip() or SEM_TEXTO) + "\n")
        if nome in disp.POR_CHAVE:
            nomes = ", ".join(f"[`{n}`](tools.md#{_ancora(n)})" for n in sorted(disp.POR_CHAVE[nome]))
            linhas.append(f"\nTools behind this key: {nomes}.\n")
    return "".join(linhas)


# ── CLI ──────────────────────────────────────────────────────────────────────

def _acoes_de(parser):
    import argparse as ap
    for a in parser._actions:
        if isinstance(a, (ap._HelpAction, ap._VersionAction)):
            continue
        yield a


def _subparsers(parser):
    import argparse as ap
    for a in parser._actions:
        if isinstance(a, ap._SubParsersAction):
            ajuda = {c.dest: c.help for c in a._choices_actions}
            for nome, sub in a.choices.items():
                yield nome, ajuda.get(nome, ""), sub


def _linha_de_opcao(a) -> str:
    nomes = ", ".join(f"`{o}`" for o in a.option_strings) or f"`{a.dest}`"
    escolhas = (" (one of: " + ", ".join(f"`{c}`" for c in a.choices) + ")") if a.choices else ""
    padrao = ""
    if a.option_strings and a.default not in (None, False, "", [], argparse.SUPPRESS):
        padrao = f" Default: {_valor(a.default)}."
    return f"| {nomes} | {_celula((a.help or '') + escolhas)}{_celula(padrao)} |\n"


def _bloco_cli(caminho: str, ajuda: str, parser, linhas: list, nivel: int) -> None:
    linhas.append(f"\n{'#' * nivel} `{caminho}`\n\n")
    if ajuda:
        linhas.append(_celula(ajuda) + "\n\n")
    acoes = [a for a in _acoes_de(parser) if not isinstance(a, argparse._SubParsersAction)]
    if acoes:
        linhas.append("| Argument | Description |\n|---|---|\n")
        linhas.extend(_linha_de_opcao(a) for a in acoes)
    for nome, ajuda_sub, sub in _subparsers(parser):
        _bloco_cli(f"{caminho} {nome}", ajuda_sub, sub, linhas, min(nivel + 1, 4))


def pagina_cli() -> str:
    from delegation_core.cli import construir_parser
    parser, _ = construir_parser()
    comandos = sorted(_subparsers(parser), key=lambda x: x[0])
    linhas = [CABECALHO, "# Command line (`delegation-core`)\n\n",
              f"**{len(comandos)} commands.** Every command that touches the index hands the work to the\n"
              "running daemon instead of opening a second copy of it.\n\n",
              "| Command | What it does |\n|---|---|\n"]
    for nome, ajuda, _ in comandos:
        linhas.append(f"| [`{nome}`](#{_ancora('delegation-core-' + nome)}) | {_celula(ajuda)} |\n")
    for nome, ajuda, sub in comandos:
        _bloco_cli(f"delegation-core {nome}", ajuda, sub, linhas, 2)
    return "".join(linhas)


# ── schedule and alerts ──────────────────────────────────────────────────────

def pagina_agenda() -> str:
    from delegation_core import vigia
    textos = _textos("schedule")
    linhas = [CABECALHO, "# Scheduled tasks\n\n",
              "With `agenda_enabled` on, the daemon runs these tasks by cron (local time). `agenda_tarefas`\n"
              "in `config.json` replaces the list; each entry may set `\"ligada\": false` to keep a task\n"
              "defined but off. `schedule_list` shows next run, last result and consecutive failures;\n"
              "`schedule_run` runs one now.\n\n",
              "| Task | Cron | Action | Arguments | What it does |\n|---|---|---|---|---|\n"]
    for t in vigia.TAREFAS_PADRAO:
        args = _valor(t.get("argumentos", {})) if t.get("argumentos") else ""
        o_que = textos.get(t["nome"], {}).get("description", "").strip() or SEM_TEXTO
        linhas.append(f"| `{t['nome']}` | `{t['cron']}` | `{t['acao']}` | {_celula(args)} | {_celula(o_que)} |\n")
    return "".join(linhas)


def pagina_alertas() -> str:
    from delegation_core import vigia
    textos = _textos("alerts")
    regras = vigia.regras_padrao() if hasattr(vigia, "regras_padrao") else None
    if regras is None:
        raise SystemExit("vigia.regras_padrao() nao existe: o gerador precisa da lista de regras")
    linhas = [CABECALHO, "# Alert rules\n\n",
              "The `alertas` task evaluates these rules every 10 minutes. An alert opens only after its\n"
              "condition has held for the waiting period, so a blip is not an alert; it closes by itself\n"
              "when the condition clears. `alerts` lists open alerts and recent events; `alerts_check`\n"
              "evaluates now.\n\n",
              "Severities are the values the program reports: `info`, `aviso` (warning) and `critico`\n"
              "(critical).\n\n",
              "| Rule | Severity | Waits | What it watches |\n|---|---|---|---|\n"]
    for r in regras:
        espera = f"{int(r.para_s)} s" if getattr(r, "para_s", 0) else "no wait"
        o_que = textos.get(r.nome, {}).get("description", "").strip() or SEM_TEXTO
        linhas.append(f"| `{r.nome}` | `{r.severidade}` | {espera} | {_celula(o_que)} |\n")
    return "".join(linhas)


# ── dashboard API ────────────────────────────────────────────────────────────

def _rotas_do_painel():
    arvore = ast.parse((SRC / "dashboard_api.py").read_text(encoding="utf-8"))
    rotas = []
    for no in ast.walk(arvore):
        if not (isinstance(no, ast.FunctionDef) and no.name in ("_route_get", "_route_post")):
            continue
        metodo = "GET" if no.name == "_route_get" else "POST"
        for x in ast.walk(no):
            if not isinstance(x, ast.If):
                continue
            teste = x.test
            caminho = None
            if (isinstance(teste, ast.Compare) and len(teste.comparators) == 1
                    and isinstance(teste.ops[0], ast.Eq)
                    and isinstance(teste.comparators[0], ast.Constant)
                    and str(teste.comparators[0].value).startswith("/api/")):
                caminho = teste.comparators[0].value
            elif (isinstance(teste, ast.Call) and isinstance(teste.func, ast.Attribute)
                    and teste.func.attr == "startswith" and teste.args
                    and isinstance(teste.args[0], ast.Constant)
                    and str(teste.args[0].value).startswith("/api/")):
                caminho = teste.args[0].value + "…"
            if caminho is None:
                continue
            alvo = ""
            for y in ast.walk(ast.Module(body=x.body, type_ignores=[])):
                if (isinstance(y, ast.Call) and isinstance(y.func, ast.Attribute)
                        and isinstance(y.func.value, ast.Name) and y.func.value.id == "self"
                        and y.func.attr.startswith("_handle")):
                    alvo = y.func.attr
                    break
            rotas.append((caminho, metodo, alvo))
    return sorted(set(rotas))


def pagina_painel() -> str:
    import inspect

    from delegation_core import dashboard_api
    rotas = _rotas_do_painel()
    linhas = [CABECALHO, "# Dashboard HTTP API\n\n",
              f"The dashboard talks to the daemon through **{len(rotas)} routes**. Every route needs the\n"
              "`Authorization: Bearer <token>` header (the same token the MCP clients use); only the\n"
              "static page itself is served without it.\n\n",
              "| Method | Path | Handler | What it does |\n|---|---|---|---|\n"]
    classe = next(c for _, c in inspect.getmembers(dashboard_api, inspect.isclass)
                  if hasattr(c, "_route_get"))
    for caminho, metodo, alvo in rotas:
        doc = ""
        if alvo and hasattr(classe, alvo):
            doc = (inspect.getdoc(getattr(classe, alvo)) or "").split("\n\n")[0]
        linhas.append(f"| {metodo} | `{caminho}` | `{alvo}` | {_celula(doc) or SEM_TEXTO} |\n")
    return "".join(linhas)


# ── environment and errors ───────────────────────────────────────────────────

def pagina_ambiente() -> str:
    textos = _textos("environment")
    usos: dict[str, set] = {}
    for arq in sorted(SRC.rglob("*.py")):
        for n, linha in enumerate(arq.read_text(encoding="utf-8").splitlines(), 1):
            for nome in re.findall(r"\b(DELEGATION_CORE_[A-Z0-9_]+)\b", linha):
                usos.setdefault(nome, set()).add(f"{arq.relative_to(SRC).as_posix()}")
    linhas = [CABECALHO, "# Environment variables\n\n",
              "| Variable | Read in | What it does |\n|---|---|---|\n"]
    for nome in sorted(usos):
        o_que = textos.get(nome, {}).get("description", "").strip() or SEM_TEXTO
        onde = ", ".join(f"`{u}`" for u in sorted(usos[nome]))
        linhas.append(f"| `{nome}` | {onde} | {_celula(o_que)} |\n")
    return "".join(linhas)


def pagina_erros() -> str:
    linhas = [CABECALHO, "# Errors a tool can return\n\n",
              "Every tool returns errors as JSON with `error`, `error_type` and `retryable`. This is the\n"
              "catalog of the visible ones, ranked by harm (`delegation-core errors-catalog` keeps\n"
              "`docs/erros-visiveis.csv` in step with the code).\n\n",
              "| Rank | Tool or function | Type | Retryable | Has a remedy | Message |\n|---|---|---|---|---|---|\n"]
    with (RAIZ / "docs" / "erros-visiveis.csv").open(encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            linhas.append(f"| {r['harm_rank']} | `{r['function']}` | {r['error_type']} | {r['retryable']} | "
                          f"{r['has_remedy']} | {_celula(r['message'])} |\n")
    return "".join(linhas)


# ── index ────────────────────────────────────────────────────────────────────

PAGINAS = {
    "tools.md": pagina_ferramentas,
    "feature-flags.md": pagina_flags,
    "config.md": pagina_config,
    "cli.md": pagina_cli,
    "schedule.md": pagina_agenda,
    "alerts.md": pagina_alertas,
    "dashboard-api.md": pagina_painel,
    "environment.md": pagina_ambiente,
    "errors.md": pagina_erros,
}


def pagina_indice() -> str:
    titulos = {
        "tools.md": "MCP tools", "feature-flags.md": "Feature flags", "config.md": "Configuration keys",
        "cli.md": "Command line", "schedule.md": "Scheduled tasks", "alerts.md": "Alert rules",
        "dashboard-api.md": "Dashboard HTTP API", "environment.md": "Environment variables",
        "errors.md": "Errors a tool can return",
    }
    linhas = [CABECALHO, "# Reference\n\n",
              "Generated from the code by `scripts/gerar_referencia.py`; the test suite fails when a page\n"
              "here no longer matches the code.\n\n"]
    linhas.extend(f"- [{titulos[p]}]({p})\n" for p in PAGINAS)
    return "".join(linhas)


def renderizar() -> dict[str, str]:
    saida = {nome: f() for nome, f in PAGINAS.items()}
    saida["README.md"] = pagina_indice()
    return saida


def sem_texto(paginas: dict[str, str]) -> dict[str, int]:
    return {n: c.count(SEM_TEXTO) for n, c in paginas.items() if SEM_TEXTO in c}


def main() -> int:
    ap_ = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap_.add_argument("--check", action="store_true", help="exit 1 if any page on disk is stale")
    args = ap_.parse_args()
    paginas = renderizar()
    velhas = [n for n, c in paginas.items()
              if not (DESTINO / n).exists() or (DESTINO / n).read_text(encoding="utf-8") != c]
    if args.check:
        for n in velhas:
            print(f"stale: docs/reference/{n}")
        for n, k in sem_texto(paginas).items():
            print(f"undocumented entries: {k} in docs/reference/{n}")
        return 1 if velhas else 0
    DESTINO.mkdir(parents=True, exist_ok=True)
    for n, c in paginas.items():
        (DESTINO / n).write_text(c, encoding="utf-8", newline="\n")
    print(f"{len(paginas)} pages in docs/reference/ ({len(velhas)} changed)")
    for n, k in sem_texto(paginas).items():
        print(f"  {k} undocumented entries in {n}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
